//! Софтверный 3D-растеризатор.
//!
//! Крейт чисто библиотечный: демо-сцена лежит в `examples/demo.rs` и
//! подключает движок так же, как это сделал бы чужой проект — через публичный
//! API. Благодаря этому движок одинаково доступен интеграционным тестам в
//! `tests/`, примерам в `examples/` и doc-тестам, а чего не хватит любому из
//! них — то дырка в публичном API.

/// `winit` целиком, как его видит движок.
///
/// Реэкспорт, а не «пусть пользователь подключит сам», и причина техническая.
/// Наружу из публичного API торчат чужие типы: `EventLoop` нужен, чтобы
/// запустить цикл, `KeyCode` — чтобы прочитать ввод. Если игра объявит `winit`
/// своей зависимостью и версия разойдётся с нашей хотя бы в минорной цифре,
/// в графе окажутся ДВА разных `winit`, и его типы перестанут совпадать с
/// нашими. Ошибка при этом выглядит абсурдно — «expected `KeyCode`, found
/// `KeyCode`», — и упирается в строчку, которая на вид совершенно правильная.
///
/// Через реэкспорт разойтись невозможно: версия всегда ровно та, с которой
/// собран движок, а `winit` в `Cargo.toml` игры вообще не нужен.
pub use winit;

/// Код клавиши. Тот же самый тип, что и `winit::keyboard::KeyCode`, просто
/// под рукой: он нужен в каждой игре, а ходить за ним через два чужих модуля
/// незачем
pub use winit::keyboard::KeyCode;

