//! Мир и всё, из чего он собран: геометрия, ресурсы, объекты, сцена и
//! превращение сцены в список треугольников.
//!
//! Раскладка та же, что у `math`: по файлу на смысловую единицу, подмодули
//! закрытые, наружу торчат только реэкспорты. Путь к типу поэтому один —
//! `scene::Mesh`, а не ещё и `scene::mesh::Mesh`, — и ни один `use` снаружи
//! от этой перекладки не изменился.
//!
//! Границы между файлами не произвольные, а по срокам жизни и по тому, кто
//! кого знает:
//!
//! - `mesh` — геометрия в локальных координатах. Про мир не знает ничего.
//! - `assets` — арены мешей и текстур и хендлы в них. Переживают любую сцену.
//! - `instance` — объект в мире: хендл меша плюс где он стоит и как окрашен.
//! - `world` — сама [`Scene`]: список инстансов, камера и три точки входа
//!   в отрисовку.
//! - `pipeline` — вершинный этап и растеризация. Единственный файл, который
//!   знает и про сцену, и про растеризатор сразу, и самый большой из них.
//!
//! Отдельный `pipeline` — не просто «чтобы файлы были поменьше». Конвейер
//! кадра втрое длиннее самой сцены и целиком состоит из внутренней кухни
//! (`RasterJob`, `VertexScratch`, нарезка на полосы), которая наружу не видна
//! и видна быть не должна. Пока всё лежало в одном файле, публичный API сцены
//! приходилось выискивать между ними.

