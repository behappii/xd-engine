//! Текстура и её выборка.
//!
//! Текстура — это картинка, которую растеризатор читает в каждом пикселе по
//! интерполированным UV-координатам. Вся хитрость не здесь, а в том, КАК до
//! неё доезжает UV: барицентрики считаются на экране, уже после перспективного
//! деления, поэтому интерполировать u и v напрямую нельзя — см.
//! `draw_triangle_filled`.
//!
//! Второй слой хитрости — сколько текселей приходится на один пиксель экрана.
//! Пока их меньше одного, картинка растянута и лечится билинейной выборкой;
//! когда их становится много, в один пиксель попадает целая пачка текселей, и
//! взять из неё один — это алиасинг: при малейшем движении камеры выбранный
//! тексель прыгает, и мелкие детали начинают кипеть. Отсюда мип-уровни.

use crate::math::{Vec2, Vec3};

/// Что делать, когда текселей на пиксель МЕНЬШЕ одного — картинка растянута.
///
/// Так выглядит любая поверхность вблизи камеры
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Magnify {
    /// Тот тексель, в который попала координата. Видны крупные квадраты —
    /// и это ровно то, что нужно пиксель-арту и отладочной шахматке
    #[default]
    Nearest,
    /// Четыре соседних текселя, взвешенных по расстоянию до их центров.
    ///
    /// Смягчает всегда примерно ТЕКСЕЛЬ шириной, сколько бы экранных пикселей
    /// он ни занимал. Поэтому на мелкой картинке выходит не «резкий край с
    /// мягким переходом», а сплошной градиент: у шахматки 4×4 тексель это
    /// четверть клетки, и смешивание идёт через всю клетку
    Linear,
}

/// Что делать, когда текселей на пиксель БОЛЬШЕ одного — картинка сжата.
///
/// Так выглядит пол, уходящий к горизонту
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Minify {
    /// Ближайший сосед на исходной картинке. Из пачки текселей, попавших
    /// в пиксель, берётся один — отсюда рябь: при малейшем сдвиге камеры
    /// выбранный меняется, и мелкие детали кипят
    #[default]
    Nearest,
    /// Билинейно, но всё ещё по исходной картинке.
    ///
    /// Рябь почти не лечит, и это не недоработка: четыре соседних текселя из
    /// сотни, попавшей в пиксель, — всё та же случайная выборка
    Linear,
    /// Мип-уровни: пирамида всё более усреднённых копий, уровень выбирается
    /// по размеру отпечатка пикселя, между соседними уровнями — плавный
    /// переход. Вот это рябь и лечит
    Mipmapped,
}

impl Minify {
    /// Чем эта настройка фильтрует ВНУТРИ одного уровня.
    ///
    /// Нужно, чтобы понять, отличается ли поведение при сжатии от поведения
    /// при растяжении: если нет, производные можно не считать вовсе
    fn within_level(self) -> Magnify {
        match self {
            Minify::Nearest => Magnify::Nearest,
            Minify::Linear | Minify::Mipmapped => Magnify::Linear,
        }
    }
}

/// Один уровень мип-пирамиды. Уровень 0 — исходная картинка, каждый следующий
/// вдвое мельче по обеим сторонам
#[derive(Debug, Clone)]
struct Level {
    width: u32,
    height: u32,
    texels: Vec<Vec3>,
}

impl Level {
    #[inline]
    fn at(&self, x: u32, y: u32) -> Vec3 {
        self.texels[(y * self.width + x) as usize]
    }
}

/// Растровая картинка, из которой берётся цвет поверхности.
///
/// Тексели хранятся уже в виде `Vec3` с компонентами 0..1, а не байтами.
/// Памяти это стоит втрое, но выборка происходит в самом горячем месте
/// движка — на каждый закрашенный пиксель, — и делить там три байта на 255
/// незачем: преобразование делается один раз при загрузке
#[derive(Debug, Clone)]
pub struct Texture {
    /// Всегда непустой; `levels[0]` — исходная картинка. Длина больше единицы
    /// только при `Minify::Mipmapped`
    levels: Vec<Level>,
    magnify: Magnify,
    minify: Minify,
}

impl Texture {
    /// Собрать текстуру из готовых текселей построчно, слева направо
    /// и сверху вниз.
    ///
    /// Паникует на пустом размере и на несовпадении длины: текстура нулевой
    /// ширины сломала бы выборку делением на ноль, а «почти правильная»
    /// длина — это опечатка, которую лучше поймать сразу, чем разглядывать
    /// потом косые полосы на модели
    pub fn new(width: u32, height: u32, texels: Vec<Vec3>) -> Self {
        assert!(width > 0 && height > 0, "текстура нулевого размера");
        assert_eq!(
            texels.len(),
            (width * height) as usize,
            "текселей не столько, сколько обещает размер"
        );

        Self {
            levels: vec![Level {
                width,
                height,
                texels,
            }],
            magnify: Magnify::default(),
            minify: Minify::default(),
        }
    }

    /// Собрать текстуру из потока байтов RGBA — того вида, в котором картинка
    /// приезжает из файла. Альфа отбрасывается: смешивания в пайплайне нет
    pub fn from_rgba8(width: u32, height: u32, bytes: &[u8]) -> Self {
        let texels = bytes
            .chunks_exact(4)
            .map(|p| {
                Vec3::new(
                    p[0] as f32 / 255.0,
                    p[1] as f32 / 255.0,
                    p[2] as f32 / 255.0,
                )
            })
            .collect();

        Self::new(width, height, texels)
    }

    /// Загрузить текстуру из файла картинки (PNG или JPEG).
    ///
    /// Единственное место в проекте, где сознательно взят внешний крейт:
    /// внутри PNG лежит поток, сжатый zlib (Хаффман + LZ77), и свой
    /// распаковщик — это неделя работы над архиватором, а не над движком.
    ///
    /// Путь считается от каталога, откуда запущен процесс; `cargo run` берёт
    /// корень проекта, поэтому `"textures/floor.png"` работает как есть
    pub fn load(path: impl AsRef<std::path::Path>) -> Result<Self, image::ImageError> {
        Ok(Self::from_dynamic(image::open(path)?))
    }

    /// То же, но из байтов, уже лежащих в памяти: формат определяется по
    /// сигнатуре в начале данных, а не по расширению.
    ///
    /// Нужно для `include_bytes!` — тогда картинка вшивается в исполняемый
    /// файл и не зависит от рабочего каталога
    pub fn decode(bytes: &[u8]) -> Result<Self, image::ImageError> {
        Ok(Self::from_dynamic(image::load_from_memory(bytes)?))
    }

    /// Общий хвост обоих загрузчиков.
    ///
    /// `into_rgba8` приводит что угодно — палитру, оттенки серого, 16 бит на
    /// канал — к единственному раскладу, который понимает `from_rgba8`.
    /// Строки в нём идут сверху вниз, то есть ровно так, как ждёт `sample`:
    /// переворачивать ничего не надо.
    ///
    /// Чего этот путь НЕ делает — не смотрит в EXIF. Фотография с телефона,
    /// снятая боком, лежит в файле как есть, а «правильный» поворот записан
    /// отдельным тегом; на текстуре это выйдет картинкой набок
    fn from_dynamic(image: image::DynamicImage) -> Self {
        let rgba = image.into_rgba8();

        Self::from_rgba8(rgba.width(), rgba.height(), rgba.as_raw())
    }

    /// Шахматка `cells`×`cells` клеток на квадрате `size`×`size` текселей.
    ///
    /// Процедурная текстура нужна раньше загрузки картинок из файла, и не для
    /// красоты: на шахматке перспективная коррекция видна безошибочно. Если
    /// UV интерполировать линейно по экрану, клетки на грани, повёрнутой к
    /// камере под углом, изогнутся — на градиенте такое можно и проглядеть,
    /// на прямых линиях нет
    pub fn checker(size: u32, cells: u32, a: [u8; 4], b: [u8; 4]) -> Self {
        let size = size.max(1);
        let cells = cells.max(1);

        let color_a = unpack(a);
        let color_b = unpack(b);

        let mut texels = Vec::with_capacity((size * size) as usize);

        for y in 0..size {
            for x in 0..size {
                // Номер клетки: сначала умножаем, потом делим. Наоборот
                // (x / (size / cells)) было бы неверно — при size, не кратном
                // cells, сторона клетки в текселях дробная, и целочисленное
                // size / cells её теряет; 10 текселей на 4 клетки дали бы
                // размер 2 вместо 2.5 и лишнюю пятую клетку с краю
                let cell_x = x * cells / size;
                let cell_y = y * cells / size;

                // Соседние по диагонали клетки одного цвета — отсюда чётность суммы
                texels.push(if (cell_x + cell_y).is_multiple_of(2) {
                    color_a
                } else {
                    color_b
                });
            }
        }

        Self::new(size, size, texels)
    }

    /// Выбрать фильтрацию: отдельно для растянутой картинки, отдельно для
    /// сжатой.
    ///
    /// Две настройки, а не одна лесенка «дёшево → дорого», потому что лесенкой
    /// не выражается нужное сочетание: `Nearest` при растяжении плюс
    /// `Mipmapped` при сжатии. Это ровно то, чего хочет пиксель-арт и любая
    /// нарочно мелкая картинка — вблизи резкие квадраты, вдали никакой ряби.
    /// Одним переключателем пришлось бы выбирать: либо рябит, либо мылит.
    ///
    /// Хранения не касается: `Minify::Mipmapped` пирамиду не строит, а лишь
    /// разрешает ею пользоваться. Строит её [`Texture::with_mipmaps`], и это
    /// разделение намеренное — см. её доку
    pub fn with_filter(mut self, magnify: Magnify, minify: Minify) -> Self {
        self.magnify = magnify;
        self.minify = minify;
        self
    }

    /// Построить мип-пирамиду: каждый следующий уровень вдвое мельче
    /// предыдущего, вплоть до одного текселя. Стоит трети лишней памяти.
    ///
    /// Отдельно от [`Texture::with_filter`], потому что это решения РАЗНОГО
    /// рода: пирамида — про то, что лежит в памяти, фильтр — про то, как из
    /// неё читают. Раньше они были склеены, и выходило, что настройка качества
    /// выборки перевыделяет память. В настоящих движках наоборот: мипы
    /// генерируются почти всегда, а сэмплер только решает, читать их или нет,
    /// — и ползунок «фильтрация» в настройках графики поэтому ничего не
    /// перестраивает, он правит несколько крошечных объектов-сэмплеров.
    ///
    /// Расцепление нужно и нам, если когда-нибудь появится такой ползунок:
    /// иначе он дёргал бы пирамиды всех текстур сразу.
    ///
    /// Вызывать повторно безопасно: у готовой пирамиды работы нет
    pub fn with_mipmaps(mut self) -> Self {
        self.build_mipmaps();
        self
    }

    pub fn magnify(&self) -> Magnify {
        self.magnify
    }

    pub fn minify(&self) -> Minify {
        self.minify
    }

    pub fn width(&self) -> u32 {
        self.levels[0].width
    }

    pub fn height(&self) -> u32 {
        self.levels[0].height
    }

    /// Сколько уровней в пирамиде. Единица — пирамиды нет
    pub fn mip_levels(&self) -> usize {
        self.levels.len()
    }

    /// Есть ли у текстуры мип-пирамида. Про фильтр ничего не говорит
    pub fn has_mipmaps(&self) -> bool {
        self.levels.len() > 1
    }

    /// Будут ли мип-уровни реально использоваться при выборке.
    ///
    /// Нужны два условия сразу: пирамида построена И фильтр её просит.
    /// `Minify::Mipmapped` без пирамиды — не ошибка, а тихий откат к уровню 0,
    /// ровно как в настоящих API: сэмплер с мип-режимом поверх картинки с
    /// одним уровнем просто всегда читает этот уровень. Ловушка отсюда
    /// очевидная — попросить мип-фильтр и забыть `with_mipmaps`, — но платить
    /// за неё скрытым выделением памяти хуже
    fn mipmapping(&self) -> bool {
        self.has_mipmaps() && self.minify == Minify::Mipmapped
    }

    /// Нужны ли этой текстуре производные UV.
    ///
    /// Растеризатор спрашивает до входа в цикл по пикселям: производные стоят
    /// нескольких умножений НА КАЖДЫЙ закрашенный пиксель, и платить за них
    /// там, где они всё равно уйдут в мусор, незачем.
    ///
    /// Нужны они в двух случаях. Очевидный — мип-уровни: без отпечатка не
    /// выбрать уровень. Менее очевидный — когда растяжение и сжатие
    /// фильтруются ПО-РАЗНОМУ: чтобы понять, какой из двух режимов сейчас,
    /// надо знать тот же самый отпечаток. Если обе настройки согласны,
    /// спрашивать не о чем, и путь по умолчанию остаётся ровно таким же
    /// быстрым, каким был до всей этой фильтрации
    pub fn needs_derivatives(&self) -> bool {
        self.mipmapping() || self.magnify != self.minify.within_level()
    }

    /// Собственно построение: каждый следующий уровень вдвое мельче
    /// и получается усреднением четвёрки текселей предыдущего.
    ///
    /// Усреднение по квадрату 2×2 — простейший из фильтров понижения, и для
    /// стороны, не кратной двойке, он приблизителен: индексы зажимаются, то
    /// есть у последнего потомка один из родителей учитывается дважды, и
    /// картинка чуть уползает вбок. Честный путь — считать вклад каждого
    /// родителя по площади перекрытия; на степенях двойки это вырождается
    /// в то же самое усреднение, поэтому цена ошибки невелика
    fn build_mipmaps(&mut self) {
        // Пирамида кончается на уровне 1×1: усреднять дальше нечего
        while self
            .levels
            .last()
            .is_some_and(|l| l.width > 1 || l.height > 1)
        {
            let src = self.levels.last().expect("цикл вошёл, значит уровень есть");

            let width = (src.width / 2).max(1);
            let height = (src.height / 2).max(1);

            let mut texels = Vec::with_capacity((width * height) as usize);

            for y in 0..height {
                for x in 0..width {
                    let x0 = (2 * x).min(src.width - 1);
                    let x1 = (2 * x + 1).min(src.width - 1);
                    let y0 = (2 * y).min(src.height - 1);
                    let y1 = (2 * y + 1).min(src.height - 1);

                    let sum = src.at(x0, y0) + src.at(x1, y0) + src.at(x0, y1) + src.at(x1, y1);

                    texels.push(sum * 0.25);
                }
            }

            self.levels.push(Level {
                width,
                height,
                texels,
            });
        }
    }

    /// Цвет текселя по текстурной координате, без учёта размера отпечатка.
    ///
    /// Соглашение: u растёт вправо, v — ВНИЗ, то есть v = 0 это верхняя строка
    /// картинки. Так лежат строки в файле, и так же считает большинство
    /// форматов; вертикальные перевороты — самый частый источник «текстура
    /// вверх ногами».
    ///
    /// Координаты за пределами 0..1 заворачиваются (режим repeat): u = 1.25
    /// это то же, что 0.25. Благодаря этому UV в развёртке можно умножать на
    /// число и получать плитку.
    ///
    /// Отпечаток пикселя тут неизвестен, поэтому считается, что картинка
    /// растянута: берётся уровень 0 и настройка `magnify`. Для настоящей
    /// отрисовки есть [`Texture::sample_grad`], а этот путь честен ровно
    /// тогда, когда [`Texture::needs_derivatives`] говорит «нет»
    #[inline]
    pub fn sample(&self, uv: Vec2) -> Vec3 {
        magnified(&self.levels[0], uv, self.magnify)
    }

    /// Цвет текселя с учётом того, насколько быстро UV меняется по экрану.
    ///
    /// `duv_dx` и `duv_dy` — насколько сдвинется координата, если шагнуть на
    /// пиксель вправо и на пиксель вниз. Из них получается ОТПЕЧАТОК пикселя
    /// в текселях, а из отпечатка — номер уровня пирамиды.
    ///
    /// Аналог `textureSampleGrad` из настоящих API. Производные берутся
    /// параметром, а не считаются внутри, потому что взяться им неоткуда:
    /// текстура видит один пиксель, а не треугольник
    #[inline]
    pub fn sample_grad(&self, uv: Vec2, duv_dx: Vec2, duv_dy: Vec2) -> Vec3 {
        if !self.needs_derivatives() {
            return self.sample(uv);
        }

        let lod = self.lod(duv_dx, duv_dy);

        // Граница между растяжением и сжатием — ровно один тексель на пиксель,
        // то есть LOD = 0. Так же её проводят и настоящие API, и там же у них
        // тот же самый шов: настройки по обе стороны разные, и переход между
        // ними получается резким, а не плавным
        if lod <= 0.0 {
            return magnified(&self.levels[0], uv, self.magnify);
        }

        if !self.mipmapping() {
            // Сжатие без пирамиды — либо её не построили, либо фильтр её и не
            // просил. Фильтровать нечем, кроме исходной картинки
            return magnified(&self.levels[0], uv, self.minify.within_level());
        }

        let top = (self.levels.len() - 1) as f32;

        // Отпечаток нулевой даёт log2(0) = -inf, испорченные производные — NaN.
        // NaN не проходит ни одно сравнение, поэтому попадает в последнюю ветку
        // Отрицательный сюда уже не попадёт, а вот +inf от испорченных
        // производных — вполне; NaN не проходит ни одно сравнение и падает
        // в последнюю ветку
        let lod = if lod.is_finite() {
            lod.min(top)
        } else if lod > 0.0 {
            top
        } else {
            0.0
        };

        let coarse_index = lod as usize;
        let fine = bilinear(&self.levels[coarse_index], uv);

        let blend = lod - coarse_index as f32;

        if blend <= 0.0 {
            return fine;
        }

        // Плавный переход между уровнями — третья «линейность» в слове
        // «трилинейная». Без неё на полу видна резкая граница там, где
        // выборка перескакивает с уровня на уровень
        let coarse = bilinear(&self.levels[coarse_index + 1], uv);

        fine + (coarse - fine) * blend
    }

    /// Номер уровня пирамиды для отпечатка заданного размера.
    ///
    /// Смысл: уровень N вдвое мельче уровня N-1, значит удвоение отпечатка —
    /// ровно один уровень вниз. Обратная к удвоению функция — двоичный
    /// логарифм, отсюда `log2`.
    ///
    /// Отпечаток берётся как БОЛЬШАЯ из двух сторон, а не как их среднее:
    /// пиксель, растянутый вдоль одной оси (пол под скользящим углом — как
    /// раз такой случай), обязан размываться по худшей из них, иначе рябь
    /// останется. Плата за это — та самая нерезкость наклонных поверхностей,
    /// от которой в настоящих API спасает анизотропная фильтрация
    fn lod(&self, duv_dx: Vec2, duv_dy: Vec2) -> f32 {
        let base = &self.levels[0];
        let (width, height) = (base.width as f32, base.height as f32);

        // UV сами по себе безразмерны, а отпечаток нужен в ТЕКСЕЛЯХ: сдвиг на
        // 0.01 по u — это один тексель на картинке шириной 100 и десять на
        // картинке шириной 1000
        let dx = Vec2::new(duv_dx.x * width, duv_dx.y * height);
        let dy = Vec2::new(duv_dy.x * width, duv_dy.y * height);

        dx.length().max(dy.length()).log2()
    }
}

/// Выборка внутри одного уровня заданным способом
#[inline]
fn magnified(level: &Level, uv: Vec2, filter: Magnify) -> Vec3 {
    match filter {
        Magnify::Nearest => nearest(level, uv),
        Magnify::Linear => bilinear(level, uv),
    }
}

/// Выборка ближайшего соседа внутри одного уровня
#[inline]
fn nearest(level: &Level, uv: Vec2) -> Vec3 {
    // Дробная часть, отсчитанная ВНИЗ, а не `%`: обычный остаток в Rust
    // сохраняет знак делимого, и (-0.25) % 1.0 дало бы -0.25, то есть
    // отрицательный индекс. Нужен неотрицательный остаток: floor(-0.25)
    // это -1, и -0.25 - (-1) = 0.75 — как раз он.
    //
    // Раньше здесь стоял rem_euclid(1.0). Результат тот же во всём
    // диапазоне, но он разворачивается в fmodf плюс ветку, а вызовов два
    // на каждый закрашенный пиксель — на демо-сцене с полом замена дала
    // ~11% кадра (1600x1200: 16.96 -> 15.15 мс)
    let u = uv.x - uv.x.floor();
    let v = uv.y - uv.y.floor();

    // NaN сюда доехать не должен, но если доедет — floor вернёт NaN,
    // разность тоже, `as u32` даст 0, и вместо паники будет левый верхний
    // тексель
    let x = (u * level.width as f32) as u32;
    let y = (v * level.height as f32) as u32;

    // Зажим обязателен, и не для красоты: на крошечном отрицательном входе
    // floor даёт -1, а разность округляется вверх ровно до 1.0 — и
    // 1.0 * width это индекс за границей строки. Ошибка ровно та же, что
    // была у rem_euclid, замена её не убрала
    let x = x.min(level.width - 1);
    let y = y.min(level.height - 1);

    level.at(x, y)
}

/// Билинейная выборка внутри одного уровня: четыре соседних текселя,
/// взвешенных по расстоянию до их ЦЕНТРОВ
#[inline]
fn bilinear(level: &Level, uv: Vec2) -> Vec3 {
    let (x0, x1, fx) = neighbours(uv.x, level.width);
    let (y0, y1, fy) = neighbours(uv.y, level.height);

    // Сначала по горизонтали, потом между двумя результатами по вертикали.
    // Порядок не важен — результат тот же, это билинейность и означает
    let top = lerp(level.at(x0, y0), level.at(x1, y0), fx);
    let bottom = lerp(level.at(x0, y1), level.at(x1, y1), fx);

    lerp(top, bottom, fy)
}

/// Два соседних текселя вдоль одной оси и вес между ними.
///
/// Ключевые здесь полтексела. Координата текселя указывает на его ЦЕНТР, а
/// центр нулевого текселя — это не u = 0, а u = 0.5/width. Без этого сдвига
/// картинка съезжает на полтекселя, и выборка ровно в центре текселя вместо
/// чистого цвета даёт смесь с соседом
#[inline]
fn neighbours(coord: f32, size: u32) -> (u32, u32, f32) {
    let wrapped = coord - coord.floor();
    let scaled = wrapped * size as f32 - 0.5;

    let floor = scaled.floor();
    let weight = scaled - floor;

    // Диапазон здесь известен заранее, и это позволяет обойтись сравнениями
    // вместо остатка. `wrapped` лежит в 0..1 (с точностью до того самого
    // округления вверх до 1.0), значит scaled — в -0.5..size-0.5, а floor —
    // в -1..size-1. То есть завернуться может только один шаг в каждую
    // сторону, и полноценный rem_euclid тут был бы платой ни за что
    let low = floor as i32;
    let high = if low + 1 >= size as i32 { 0 } else { low + 1 };
    let low = if low < 0 { size as i32 - 1 } else { low };

    // Зажим на случай, если scaled всё-таки уехал за size-0.5: та же история,
    // что и у ближайшего соседа с округлением вверх до 1.0
    (
        (low as u32).min(size - 1),
        (high as u32).min(size - 1),
        weight,
    )
}

#[inline]
fn lerp(a: Vec3, b: Vec3, t: f32) -> Vec3 {
    a + (b - a) * t
}

/// Цвет из байтов в вектор с компонентами 0..1
fn unpack(color: [u8; 4]) -> Vec3 {
    Vec3::new(
        color[0] as f32 / 255.0,
        color[1] as f32 / 255.0,
        color[2] as f32 / 255.0,
    )
}

