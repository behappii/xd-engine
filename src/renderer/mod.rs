//! Фрагментный этап: из готовых треугольников получаются пиксели.
//!
//! Сцена сюда не видна вообще — на вход приходят [`ShadedVertex`] с уже
//! посчитанными атрибутами и [`DrawContext`] с буферами. Это и есть граница
//! между двумя этапами конвейера, та же, что между вершинным и фрагментным
//! шейдером на GPU.
//!
//! Раскладка та же, что у `math` и `scene`: по файлу на смысловую единицу,
//! подмодули закрытые, наружу только реэкспорты.
//!
//! - `shaded_vertex` — что приезжает на вход: позиция в clip space плюс
//!   интерполируемые атрибуты.
//! - `context` — куда пишем: буферы кадра и глубины (точнее, полоса из них)
//!   и запись пикселя. Единственное место, где считается индекс в буфере.
//! - `screen` — перевод clip space → NDC → пиксели.
//! - `triangle` — залитый треугольник: барицентрики, перспективная коррекция,
//!   текстура, тест глубины. Самый большой файл и главное содержимое модуля.
//! - `wireframe` — проволочный режим: рёбра, отсечение линии и Брезенхем.
//!
//! Залитый треугольник и проволока разведены нарочно, хотя оба «рисуют
//! треугольник». Общего у них ровно ничего: у проволоки нет ни атрибутов, ни
//! интерполяции, ни теста глубины, и ходит она через совсем другой клиппер
//! (`clip_line_4d` вместо `clip_triangle_near`). Пока они лежали вперемешку,
//! это было незаметно, а из-за этого легко решить, что проволока просто
//! «дешёвый режим» заливки, и начать сводить их вместе.

