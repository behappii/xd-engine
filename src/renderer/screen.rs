//! Дорога из clip space в пиксели: перспективное деление и перевод NDC
//! в экранные координаты.
//!
//! Обе формы перевода лежат рядом нарочно, хотя пользуются ими разные файлы.
//! Разница между ними ровно в одном — округлении, — и она принципиальна:
//! линии рисуются по целым пикселям, а залитый треугольник считает
//! барицентрики в f32, и округление краёв до отрисовки сдвинуло бы их на
//! полпикселя. Лежали бы они в разных файлах — эту пару было бы не заметить,
//! и рано или поздно кто-нибудь свёл бы их в одну.

use crate::math::{Vec3, Vec4};

// Perspective Divide
pub(super) fn clip_to_ndc(v: Vec4) -> Vec3 {
    Vec3 {
        x: v.x / v.w,
        y: v.y / v.w,
        z: v.z / v.w,
    }
}

// Viewport Transform
pub(super) fn ndc_to_screen(v: Vec3, width: u32, height: u32) -> (i32, i32) {
    let x = ((v.x + 1.0) * 0.5 * width as f32).round() as i32;

    let y = ((1.0 - v.y) * 0.5 * height as f32).round() as i32;

    (x, y)
}

/// NDC -> экран, но в f32: округление здесь убило бы точность краёв
pub(super) fn ndc_to_screen_f(x: f32, y: f32, width: u32, height: u32) -> (f32, f32) {
    (
        (x + 1.0) * 0.5 * width as f32,
        (1.0 - y) * 0.5 * height as f32,
    )
}
