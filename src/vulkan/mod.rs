//! Второй рендер-бэкенд — голый Vulkan, написанный руками (без `wgpu`,
//! `ash`, `vulkano`), с MoltenVK на Mac. Живёт РЯДОМ с CPU-растеризатором
//! в `renderer/`/`scene/pipeline.rs`, а не вместо него — тот модуль не
//! тронут этой работой ни строкой.
//!
//! Раскладка файлов — по стадиям самого GPU-конвейера, а не по аналогии с
//! `renderer`/`scene`: там были свои причины для границ (срок жизни,
//! общий/ничего общего), а тут порядок ровно тот, в котором Vulkan сам
//! требует создавать объекты — от библиотеки до кадра на экране.
//!
//! - `loader` — свой `dlopen`/`LoadLibrary`, находит `vkGetInstanceProcAddr`
//! - `ffi` — сырые `#[repr(C)]` типы Vulkan, подмножество для текущих фаз
//! - `instance` — `VkInstance` и таблица функций уровня instance
//! - `device` — физическое и логическое устройство, таблица функций уровня
//!   device (все, что дальше принимает `VkDevice`/`VkQueue`/`VkCommandBuffer`)
//! - `surface` — платформенная поверхность окна (Metal/Win32/Xlib)
//! - `swapchain` — кольцо картинок для показа в окне
//! - `buffer` — память GPU: вершинный/индексный буфер настоящей геометрии
//!   (Фаза 2), без staging — сразу host-visible (для картинок так уже нельзя,
//!   см. `image`)
//! - `gpu_assets` — зеркало `scene::Assets` на видеокарте: буфер на каждый
//!   меш, картинка с сэмплером на каждую текстуру, догружается по мере роста
//!   арен
//! - `depth` — depth-буфер: `VkImage`+`VkImageView`, которые GPU сам
//!   заполняет во время рендеринга, без staging (Фаза 5)
//! - `image` — `VkImage`+`VkImageView` текстуры: staging-буфер, копия в
//!   device-local память, переходы раскладки (Фаза 4)
//! - `sampler` — `VkSampler`, собранный из `Magnify`/`Minify` текстуры
//!   (Фаза 4)
//! - `descriptor` — первый в этом движке descriptor set (сэмплер + картинка
//!   вместе, `COMBINED_IMAGE_SAMPLER`) — то, для чего push-constant не
//!   годится (Фаза 4)
//! - `shader` — сырой SPIR-V вершинного и фрагментного шейдера, собранный
//!   вручную маленьким внутренним ассемблером (не GLSL-компилятором)
//! - `pipeline` — render pass и графический пайплайн
//! - `sync` — синхронизация одного кадра между CPU и GPU
//! - `context` — `VulkanRenderer`, единственная публичная точка входа
//!
//! Фаза 1 («hello triangle») — треугольник, зашитый в вершинный шейдер, без
//! буферов и без текстур. Фаза 2 — настоящий куб (`scene::Mesh::create_cube`)
//! через вершинный/индексный буфер, MVP push-константой, куб вращается.
//! Фаза 3 — ламбертово освещение прямо во vertex shader: нормаль вторым
//! атрибутом, матрица нормалей второй половиной push-константы, яркость по
//! той же формуле, что и `scene::pipeline::shade_instance` на CPU-пути, цвет
//! едет во фрагментный шейдер интерполированным атрибутом (Гуро). Фаза 4 —
//! текстура на кубе: UV третьим атрибутом, `VkSampler`/`VkImage` через
//! первый в движке descriptor set, тексель множится на цвет из Фазы 3 —
//! тот же приём, что и на CPU (`Vec3 * Vec3`, покомпонентно). Фаза 5 —
//! depth-буфер (тест глубины в пайплайне, второй attachment render pass'а)
//! и несколько инстансов куба в одном кадре, каждый со своей моделью:
//! общие вершинный/индексный буфер и дескриптор, свой push-constant на
//! `vkCmdDrawIndexed`.
//!
//! На этом пять фаз закончились, и следующим шагом бэкенд перестал быть
//! автономной демонстрацией: `VulkanRenderer::draw` принимает `&Scene` и
//! `&Assets` — те же самые, что и `Scene::draw` на CPU-пути, — а меши и
//! текстуры зеркалит на видеокарту `gpu_assets`. Игра с этого момента не
//! знает, каким бэкендом её рисуют

