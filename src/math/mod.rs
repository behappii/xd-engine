//! Своя линейная алгебра: векторы и матрица 4×4.
//!
//! По файлу на тип, и в файле лежит всё, что к типу относится: сама структура,
//! её методы, перегрузки операторов и её тесты. Раньше это был один `math.rs`
//! на 750 строк, где четыре независимых типа шли подряд, а все тесты — общей
//! кучей в конце; чтобы прочитать про `Mat4::inverse`, приходилось листать
//! мимо `Vec2`.
//!
//! Подмодули НЕ публичные, наружу торчат только реэкспорты. Так у каждого типа
//! ровно один путь — `math::Vec3`, а не ещё и `math::vec3::Vec3`, — и внутреннюю
//! раскладку файлов можно менять дальше, не ломая ничей `use`.

mod mat4;
mod vec2;
mod vec3;
mod vec4;

pub use mat4::Mat4;
pub use vec2::Vec2;
pub use vec3::Vec3;
pub use vec4::Vec4;

/// Общее хозяйство тестов модуля.
///
/// Живёт здесь, а не в каком-то одном из файлов, потому что нужно сразу
/// нескольким: сравнение векторов с допуском пригождается и `Vec3`, и `Mat4`
#[cfg(test)]
pub(crate) mod testing {
    use super::Vec3;

    /// Свой допуск, а не config::EPSILON: тот задаёт геометрический порог
    /// в клиппинге, а здесь речь про накопленную ошибку f32
    pub const EPS: f32 = 1e-5;

    pub fn assert_vec3_eq(actual: Vec3, expected: Vec3) {
        let d = actual - expected;

        assert!(
            d.length() < EPS,
            "ожидали {:?}, получили {:?}",
            expected,
            actual
        );
    }
}
