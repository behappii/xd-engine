/// Однородные координаты: позиция в clip space, ещё до перспективного деления.
///
/// Ни методов, ни операторов у него нет, и это не недоделка. `Vec4` в движке
/// не самостоятельный вектор, а промежуточное состояние позиции между
/// умножением на MVP и делением на `w`: дальше он либо превращается в `Vec3`
/// (`renderer::clip_to_ndc`), либо режется по плоскости. Единственная нужная
/// ему арифметика — линейная интерполяция вдоль ребра, и она лежит рядом с
/// алгоритмом, которому нужна (`clipping::lerp_vec4`).
///
/// Именно из-за `w` тут нельзя пользоваться `Vec3`: `w` хранит расстояние до
/// камеры, на нём держатся и перспективная коррекция, и depth-буфер
#[derive(Debug, Clone, Copy)]
pub struct Vec4 {
    pub x: f32,
    pub y: f32,
    pub z: f32,
    pub w: f32,
}
