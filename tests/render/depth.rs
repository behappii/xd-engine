//! Depth-буфер: кто кого закрывает и кто выигрывает при равной глубине.

use xd_engine::{
    math::Vec3,
    scene::{Instance, Mesh},
};

use crate::harness::{World, render};

/// Проволочный куб и залитая стена на весь экран. `wire_z` задаёт, кто из них
/// ближе к камере, `wire_first` — кого рисуют раньше.
///
/// Оба параметра нужны порознь: правильный результат зависит ТОЛЬКО от `wire_z`,
/// а вот сломать его можно по-разному, и какой именно поломкой — решает
/// `wire_first`. Возвращает число зелёных пикселей, то есть уцелевшую проволоку
fn wire_pixels_against_a_wall(wire_z: f32, wire_first: bool) -> usize {
    let mut world = World::new();

    let cube = world.add_mesh(Mesh::create_cube());

    let mut wire = Instance::new(cube, Vec3::new(0.0, 0.0, wire_z))
        .with_color([0, 255, 0, 255])
        .as_wireframe();
    wire.scale = Vec3::new(0.5, 0.5, 0.5);
    wire.rotation = Vec3::new(20.0, 35.0, 0.0);

    // Стена: плоский куб во весь экран, ровно посередине между двумя
    // возможными положениями проволоки
    let mut wall = Instance::new(cube, Vec3::new(0.0, 0.0, 0.0)).with_color([120, 120, 200, 255]);
    wall.scale = Vec3::new(6.0, 6.0, 0.1);

    if wire_first {
        world.add_instance(wire);
        world.add_instance(wall);
    } else {
        world.add_instance(wall);
        world.add_instance(wire);
    }

    render(&world)
        .chunks_exact(4)
        .filter(|p| **p == [0, 255, 0, 255])
        .count()
}

#[test]
fn a_wireframe_in_front_is_not_erased_by_what_is_drawn_after_it() {
    // Регрессия, замеченная на демо-сцене: проволочный куб пропадал кусками
    // или целиком на фоне пола, текстурированных объектов и разноцветного
    // куба. Общее у них одно — все они добавлены в сцену ПОЗЖЕ проволоки.
    //
    // Проволока не трогала depth-буфер вообще: ни теста, ни записи. Значит
    // объект, нарисованный после неё, проходил свой тест глубины — в буфере
    // на месте линии по-прежнему стояла пустота — и спокойно затирал её
    // пиксели, даже стоя ДАЛЬШЕ.
    //
    // Отсюда и расстановка: проволока ближе и рисуется ПЕРВОЙ. Тут мало
    // научить её тестировать глубину — не записав свою, она снова окажется
    // стёрта стеной
    assert!(
        wire_pixels_against_a_wall(2.0, true) > 0,
        "проволока перед стеной стёрта тем, что нарисовано после неё"
    );
}

#[test]
fn a_wireframe_behind_a_wall_is_hidden_by_it() {
    // Вторая половина того же: линия обязана глубину ещё и ПРОВЕРЯТЬ.
    //
    // Расстановка зеркальная: проволока дальше и рисуется ВТОРОЙ. Одной
    // записи глубины здесь не хватит — без теста линия ляжет поверх стены,
    // сквозь которую её быть не должно
    assert_eq!(
        wire_pixels_against_a_wall(-2.0, false),
        0,
        "проволока просвечивает сквозь стену"
    );
}

#[test]
fn at_equal_depth_the_instance_added_first_wins() {
    // Порядок инстансов — это порядок отрисовки, и вершинный этап обязан его
    // сохранять, хотя инстансы расходятся по потокам как попало. Держится это
    // на том, что списки треугольников склеиваются по индексу инстанса, а не
    // по тому, кто раньше закончил.
    //
    // Увидеть порядок можно ровно там, где его не решает глубина. Два
    // совпадающих куба дают побитово одинаковую 1/w — те же вершины, те же
    // матрицы, — а тест глубины строгий: пиксель с РАВНОЙ глубиной не
    // перезаписывается. Значит выигрывает тот, кого нарисовали раньше.
    //
    // Побайтовое сравнение потоков такую ошибку не поймает: перестановка
    // применилась бы одинаково и к однопоточной ветке, и к многопоточной,
    // и кадры остались бы равны друг другу — просто оба неправильные
    let render_pair = |first: [u8; 4], second: [u8; 4]| {
        let mut world = World::new();
        let mesh = world.add_mesh(Mesh::create_cube());

        for color in [first, second] {
            let cube = world.scene.spawn(mesh, Vec3::new(0.0, 0.0, 0.0));
            cube.rotation = Vec3::new(20.0, 35.0, 0.0);
            cube.color = color;
        }

        render(&world)
    };

    const WHITE: [u8; 4] = [255, 255, 255, 255];
    const RED: [u8; 4] = [255, 0, 0, 255];

    // Чей пиксель лёг в кадр, видно по зелёному каналу: у красного куба он
    // ровно ноль, у белого не меньше фоновой подсветки (0.25 от 255 — это 63)
    let red_pixels = |frame: &[u8]| {
        frame
            .chunks_exact(4)
            .filter(|p| p[3] != 0 && p[0] > 0 && p[1] == 0)
            .count()
    };

    assert_eq!(
        red_pixels(&render_pair(WHITE, RED)),
        0,
        "красный куб добавлен вторым, но перебил первый"
    );

    // Вторая половина — проверка самой проверки: со сменой порядка кадр
    // обязан измениться, иначе тест зелен при любом коде
    assert!(
        red_pixels(&render_pair(RED, WHITE)) > 0,
        "порядок вообще ни на что не влияет — тест ничего не стережёт"
    );
}
