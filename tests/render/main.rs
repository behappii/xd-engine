//! Раскладка та же, что в `src`: по файлу на тему, общее хозяйство в
//! `harness`.
//!
//! Тестовая цель при этом ОДНА, и ради этого корень называется `main.rs`, а
//! не `render.rs`. Cargo делает отдельный бинарник из каждого файла прямо
//! в `tests/`, но каталог с `main.rs` внутри считает одной целью — соседние
//! файлы становятся её подмодулями. Разложи мы их как `tests/*.rs`, и
//! `harness` пересобирался бы в каждый бинарник, а каждый ругался бы на
//! помощников, которыми не пользуется именно он.

